package uk.ac.ox.poseidon.biology.biomass;

import static org.assertj.core.api.Assertions.assertThat;
import static org.mockito.Mockito.CALLS_REAL_METHODS;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

import org.junit.jupiter.api.Test;
import uk.ac.ox.poseidon.geography.grids.Cell;

final class BiomassGridTest {

  @Test
  void defaultBiomassAccessorWrapsTheCellsKilograms() {
    final Cell cell = new Cell(1, 2);
    final BiomassGrid grid = mock(BiomassGrid.class, CALLS_REAL_METHODS);
    when(grid.getValue(cell)).thenReturn(7.5);

    assertThat(grid.getBiomass(cell).asKg()).isEqualTo(7.5);
  }
}
